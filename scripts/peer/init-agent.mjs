import { createPublicKey } from 'node:crypto';
import { mkdir, readFile, writeFile, chmod } from 'node:fs/promises';
import { dirname, isAbsolute, resolve } from 'node:path';
import { readPrivateJson, validateTeam } from '../../packages/peer/config.mjs';
const [teamPath, identityPath, repo, dataDir, out] = process.argv.slice(2);
if (![teamPath, identityPath, repo, dataDir, out].every((v) => v && isAbsolute(v))) throw new Error('usage: node scripts/peer/init-agent.mjs /abs/team.json /abs/bob.private.json /abs/clone /abs/data /abs/bob-peer.json');
const team = validateTeam(JSON.parse(await readFile(resolve(teamPath), 'utf8')));
const identity = await readPrivateJson(resolve(identityPath));
if (!team.agents[identity.agent_id]) throw new Error('identity is not in team policy');
const publicKey = createPublicKey(identity.private_key).export({ type: 'spki', format: 'pem' });
if (publicKey !== team.agents[identity.agent_id].public_key) throw new Error('private identity does not match the public key pinned in team policy');
const config = { schema_version: 2, agent_id: identity.agent_id, repo: resolve(repo), data_dir: resolve(dataDir), team_file: resolve(teamPath), private_key: identity.private_key, test_argv: ['sh', 'test.sh'] };
await mkdir(dirname(resolve(out)), { recursive: true, mode: 0o700 });
await writeFile(resolve(out), JSON.stringify(config, null, 2) + '\n', { mode: 0o600, flag: 'wx' }); await chmod(resolve(out), 0o600);
console.log(`private peer config written: ${resolve(out)} (keep it local)`);
